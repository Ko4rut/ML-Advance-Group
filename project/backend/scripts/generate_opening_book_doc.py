"""Regenerate docs/OPENING_BOOK_V2.md from the code (run from project/backend).

    python -m scripts.generate_opening_book_doc
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

from src.environment import GameState
from src.training.opening_book import OPENING_LINES_V1, OPENING_LINES_V2
from src.training.wxf import notate_line

HEADER = """# Opening book v2 (`xiangqi-curated-v2`)

Generated by `python -m scripts.generate_opening_book_doc`. Do not edit by hand.

* v2 = all 12 frozen v1 lines + new 8-10 ply lines. Notation is WXF
  (files numbered from each player's own right; `+` forward, `-` backward,
  `=` sideways; Red moves first).
* The theory of the new lines is **best-effort**: every line is replay-validated
  by the engine and contains no capture, but names and move orders should be
  reviewed by a Xiangqi player. No ECCO codes are given on purpose.
* Final positions are all distinct except the two pairs inherited from the
  frozen v1 (marked below as `same final position as ...`).
"""


def _final_key(line):
    state = GameState.initial()
    for action in line.moves:
        state = state.moved(action)
    return state.position_key()


def build() -> str:
    v1_ids = {line.opening_id for line in OPENING_LINES_V1}
    groups = defaultdict(list)
    for line in OPENING_LINES_V2:
        groups[_final_key(line)].append(line.opening_id)

    out = [HEADER, f"Total lines: **{len(OPENING_LINES_V2)}** "
                   f"({len(OPENING_LINES_V1)} from v1, "
                   f"{len(OPENING_LINES_V2) - len(OPENING_LINES_V1)} new).\n"]

    families: dict[str, list] = defaultdict(list)
    for line in OPENING_LINES_V2:
        families[line.family].append(line)
    out.append("## Families\n")
    out.append("| family | lines |")
    out.append("|---|---|")
    for family in sorted(families):
        out.append(f"| `{family}` | {len(families[family])} |")

    out.append("\n## All lines\n")
    out.append("| opening_id | family | name | plies | WXF moves | source | note |")
    out.append("|---|---|---|---|---|---|---|")
    for line in OPENING_LINES_V2:
        notation = line.notation or notate_line(line.moves)
        notes = [line.note] if line.note else []
        twins = [i for i in groups[_final_key(line)] if i != line.opening_id]
        if twins:
            notes.append("same final position as " + ", ".join(f"`{i}`" for i in twins))
        out.append(
            f"| `{line.opening_id}` | `{line.family}` | {line.name} | {len(line.moves)} | "
            f"`{' '.join(notation)}` | {'v1' if line.opening_id in v1_ids else 'v2'} | "
            f"{'; '.join(notes)} |"
        )
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="docs/OPENING_BOOK_V2.md")
    args = parser.parse_args()
    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build(), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
